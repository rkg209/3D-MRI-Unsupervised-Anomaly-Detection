"""Anomaly-informed OpenBHB wrapper (Spec 009).

Wraps a chunk-level :class:`~mri_ad.data.datasets.OpenBHBDataset` and returns
``{"corrupted", "healthy", "synth_mask"}`` per item, generated by an
:class:`~mri_ad.synth.fpi.FPIAnomalyGenerator` against a donor drawn from a *different* OpenBHB
subject.

Determinism (Spec 009 D5, NFR-1): every item's RNG is seeded from
``blake2b(f"{seed}:{epoch}:{index}")`` — never Python's salted ``hash()`` (``PYTHONHASHSEED`` is
set by ``seed_everything`` *after* interpreter start, so ``hash()`` on a string would silently
desynchronize worker RNG streams) and never a shared/global generator (which would make
per-worker ordering observable in the result). Because each item's seed is a pure function of
``(seed, epoch, index)``, the result is identical regardless of ``num_workers`` or shuffling.

Donor selection is a **bijection**, never a rejection loop — a loop consumes a variable number of
RNG draws per item, which would desynchronize the deterministic stream depending on how many
donors happen to collide with the target::

    j = randint(0, n - 2); donor = j if j < target else j + 1
"""

from __future__ import annotations

import hashlib

import torch
from torch.utils.data import Dataset

from mri_ad.data.datasets import OpenBHBDataset
from mri_ad.exceptions import ConfigError
from mri_ad.synth.fpi import FPIAnomalyGenerator

_SEED_MASK = (1 << 63) - 1


def _item_seed(seed: int, epoch: int, index: int, *, epoch_invariant: bool) -> int:
    """``blake2b(f"{seed}:{epoch}:{index}")`` folded into a 63-bit int for ``manual_seed``."""
    epoch_component = 0 if epoch_invariant else epoch
    payload = f"{seed}:{epoch_component}:{index}".encode()
    digest = hashlib.blake2b(payload, digest_size=8).digest()
    return int.from_bytes(digest, "big") & _SEED_MASK


class AnomalyInformedDataset(Dataset):
    """``OpenBHBDataset`` chunk -> ``{"corrupted", "healthy", "synth_mask"}`` via FPI."""

    def __init__(
        self,
        base: OpenBHBDataset,
        generator: FPIAnomalyGenerator,
        *,
        seed: int,
        epoch_invariant: bool = False,
        donor_chunk: str = "same",
    ) -> None:
        """Wrap ``base``.

        Raises :class:`ConfigError` if ``donor_chunk`` is invalid or ``base`` has fewer than 2
        volumes (no distinct donor subject would exist).
        """
        if donor_chunk not in ("same", "random"):
            raise ConfigError(f"donor_chunk must be 'same' or 'random', got {donor_chunk!r}.")
        n_volumes = len(base.volume_ids)
        if n_volumes < 2:
            raise ConfigError(
                f"AnomalyInformedDataset needs >= 2 OpenBHB volumes to pick a donor, got "
                f"{n_volumes}."
            )
        self.base = base
        self.generator = generator
        self.seed = int(seed)
        self.epoch_invariant = bool(epoch_invariant)
        self.donor_chunk = donor_chunk
        self._epoch = 0
        self._chunks_per_volume = base._chunks_per_volume  # noqa: SLF001 (same-package internal)
        self._n_volumes = n_volumes

    def set_epoch(self, epoch: int) -> None:
        """Advance the per-item seed's epoch component. A no-op if ``epoch_invariant=True``."""
        self._epoch = int(epoch)

    def __len__(self) -> int:
        """Same length as the wrapped ``base`` — one corruption per chunk."""
        return len(self.base)

    def __getitem__(self, index: int) -> dict:
        """Return ``{"corrupted", "healthy", "synth_mask", "volume_index", "chunk_index"}``."""
        target = self.base[index]
        target_volume_index = int(target["volume_index"])
        target_chunk_index = int(target["chunk_index"])

        item_seed = _item_seed(self.seed, self._epoch, index, epoch_invariant=self.epoch_invariant)
        item_generator = torch.Generator().manual_seed(item_seed)

        j = int(torch.randint(0, self._n_volumes - 1, (1,), generator=item_generator).item())
        donor_volume_index = j if j < target_volume_index else j + 1

        if self.donor_chunk == "same":
            donor_chunk_index = target_chunk_index
        else:
            donor_chunk_index = int(
                torch.randint(0, self._chunks_per_volume, (1,), generator=item_generator).item()
            )

        donor_index = donor_volume_index * self._chunks_per_volume + donor_chunk_index
        donor = self.base[donor_index]

        result = self.generator.generate(target["image"], donor["image"], generator=item_generator)

        return {
            "corrupted": result.corrupted,
            "healthy": result.healthy,
            "synth_mask": result.synth_mask,
            "volume_index": target_volume_index,
            "chunk_index": target_chunk_index,
        }


__all__ = ["AnomalyInformedDataset"]
